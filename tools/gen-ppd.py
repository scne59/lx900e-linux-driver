def size_from_token(token):
    """'50x30mm' -> ('50x30mm', w_pt, h_pt, '50 x 30 mm')."""
    t = token.strip()
    if not t or t.startswith("#"):
        return None
    mm = t.endswith("mm")
    body = t[:-2] if mm else t
    if "x" not in body and "X" not in body:
        return None
    try:
        w, h = (float(v) for v in body.replace("X", "x").split("x"))
    except ValueError:
        return None
    if mm:
        w_pt, h_pt = w * 72.0 / 25.4, h * 72.0 / 25.4
        label = "%g x %g mm" % (w, h)
    else:
        w_pt, h_pt = w * 72.0, h * 72.0
        label = "%g x %g in" % (w, h)
    if not (54.0 <= w_pt <= 612.0 and 54.0 <= h_pt <= 1296.0):
        return None
    return t, w_pt, h_pt, label


def main():
    out_path = "driver/CL900-linux.ppd"
    args = sys.argv[1:]
    extra = []
    while args:
        a = args.pop(0)
        if a == "-o":
            if not args:
                sys.exit("-o needs a path")
            out_path = args.pop(0)
        elif a in ("-h", "--help"):
            print(__doc__)
            return
        else:
            extra.append(a)

    sizes = list(SIZES)
    have = {s[0] for s in sizes}
    for path in extra:
        try:
            lines = open(path, encoding="utf-8").read().splitlines()
        except OSError as e:
            sys.exit("cannot read %s: %s" % (path, e))
        for line in lines:
            got = size_from_token(line)
            if not got:
                if line.strip() and not line.strip().startswith("#"):
                    print("skipping unreadable size %r" % line, file=sys.stderr)
                continue
            name, w, h, label = got
            if name in have:
                continue
            have.add(name)
            sizes.append((name, w, h, label))

    if DEFAULT_PAGE not in have:
        sys.exit("default page %s is missing from the size table" % DEFAULT_PAGE)

    out = [HEADER]

    out.append("*OpenUI *PageSize/Media Size: PickOne\n")
    out.append("*OrderDependency: 10 AnySetup *PageSize\n")
    out.append("*DefaultPageSize: %s\n" % DEFAULT_PAGE)
    for name, w, h, label in sizes:
        out.append('*PageSize %s/%s: "<</PageSize[%g %g]/ImagingBBox null>>'
                   'setpagedevice"\n' % (name, label, w, h))
    out.append("*CloseUI: *PageSize\n")

    out.append("*OpenUI *PageRegion/Media Size: PickOne\n")
    out.append("*OrderDependency: 10 AnySetup *PageRegion\n")
    out.append("*DefaultPageRegion: %s\n" % DEFAULT_PAGE)
    for name, w, h, label in sizes:
        out.append('*PageRegion %s/%s: "<</PageSize[%g %g]/ImagingBBox null>>'
                   'setpagedevice"\n' % (name, label, w, h))
    out.append("*CloseUI: *PageRegion\n")

    out.append("*DefaultImageableArea: %s\n" % DEFAULT_PAGE)
    for name, w, h, label in sizes:
        out.append('*ImageableArea %s/%s: "0 0 %g %g"\n' % (name, label, w, h))

    out.append("*DefaultPaperDimension: %s\n" % DEFAULT_PAGE)
    for name, w, h, label in sizes:
        out.append('*PaperDimension %s/%s: "%g %g"\n' % (name, label, w, h))

    out.append(INK)
    out.append("*% End of LX900E.PPD\n")

    text = "".join(out)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d bytes, %d page sizes)" % (out_path, len(text), len(sizes)))


if __name__ == "__main__":
    main()
